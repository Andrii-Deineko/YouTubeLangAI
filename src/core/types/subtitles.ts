export interface WordToken {
  id: string;
  text: string;
  isWord: boolean;
  startTime: number;
  endTime: number;
  normalized: string;
}

export interface SubtitleCue {
  id: string;
  index?: number;
  startTime: number;
  endTime: number;
  text: string;
  tokens: WordToken[];
  translation?: string;
}

export interface SubtitleTrack {
  id: string;
  language: string;
  label: string;
  isDefault?: boolean;
  isAutoGenerated?: boolean;
  cues: SubtitleCue[];
}

export interface TrackMetadata {
  id?: string;
  videoId?: string;
  lang?: string;
  language?: string;
  label?: string;
  source?: string;
  tlang?: string;
  kind?: string;
  isAsr?: boolean;
  url?: string;
  title?: string;
}

export interface Json3Seg {
  utf8: string;
  tOffsetMs?: number;
}

export interface Json3Event {
  tStartMs: number;
  dDurationMs?: number;
  wWinId?: number;
  aAppend?: number;
  segs?: Json3Seg[];
}

export interface Json3Response {
  events?: Json3Event[];
  wireMagic?: string;
}

export interface InterceptedSubtitlePayload {
  source: 'fetch' | 'xhr' | 'playerjs';
  url?: string;
  rawText?: string;
  playerJsString?: string;
  resetPrevious?: boolean;
}
